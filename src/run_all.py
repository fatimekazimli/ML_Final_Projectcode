from __future__ import annotations

import json
import os

from . import data_prep as dp
from . import eda
from . import evaluate as ev
from . import svm_experiments as svx
from . import tree_experiments as tx

TREE_TRAIN_CAP = 5_000
REPORT_DIR = "report"
RES_DIR = "results"


def tex(s):
    s = str(s)
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")]:
        s = s.replace(a, b)
    return s


def fmt_int(x):
    return f"{int(round(x)):,}".replace(",", "{,}")


def write_numbers(d, tree, svm_test):
    info = d["info"]
    rows = {(r["task"], r["model"]): r for r in tree["rows"]}
    ours_a, ours_b = rows[("A", "Our Tree")], rows[("B", "Our Tree")]
    lin, rff = svm_test["Our SVM linear"], svm_test["Our SVM RFF"]
    macros = {
        "RawRows": fmt_int(info["raw_rows"]),
        "UniqueRows": fmt_int(info["unique_listing_rows"]),
        "CleanRows": fmt_int(info["clean_rows"]),
        "UsdRows": fmt_int(info["usd_rows"]),
        "TrainRows": fmt_int(info["train_rows"]),
        "ValRows": fmt_int(info["validation_rows"]),
        "TestRows": fmt_int(info["test_rows"]),
        "FeatureCount": str(info["feature_count"]),
        "TierThreshold": fmt_int(info["tier_threshold_AZN"]),
        "PremiumShareTrain": f"{info['class_balance']['train'] / info['train_rows'] * 100:.1f}",
        "LeakageCols": ", ".join(r"\texttt{" + tex(c) + "}" for c in info["leakage_columns"]) or "none found",
        "ExcludedCols": ", ".join(r"\texttt{" + tex(c) + "}" for c in info["excluded_columns"]),
        "TreeFitRows": fmt_int(TREE_TRAIN_CAP),
        "TreeRmse": fmt_int(ours_a["RMSE_AZN"]),
        "TreeMae": fmt_int(ours_a["MAE_AZN"]),
        "TreeRtwo": f"{ours_a['R2']:.3f}",
        "TreeFone": f"{ours_b['F1']:.3f}",
        "TreeAuc": f"{ours_b['AUC']:.3f}",
        "SvmFone": f"{lin['F1']:.3f}",
        "SvmAuc": f"{lin['AUC']:.3f}",
        "RffFone": f"{rff['F1']:.3f}",
        "RffAuc": f"{rff['AUC']:.3f}",
    }
    path = os.path.join(REPORT_DIR, "numbers.tex")
    with open(path, "w", encoding="utf-8") as f:
        f.write("% generated by python -m src.run_all, do not edit by hand\n")
        for k, v in macros.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print("saved", path)


def write_results_table(tree, svm_test, cv_b, cv_a):
    lines = [
        "% generated by python -m src.run_all, do not edit by hand",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Test-set results on the held-out split. Task A trees are fit on log(price) "
        r"and scored in AZN. Trees use the seeded " + fmt_int(TREE_TRAIN_CAP) + r"-row training sample; "
        r"SVMs and the sklearn SVM baselines use the full training split (\texttt{SVC} uses a 5{,}000-row subsample).}",
        r"\label{tab:results}",
        r"\begin{tabular}{@{}lrrrrrrr@{}}",
        r"\toprule",
        r"Model & RMSE (AZN) & MAE (AZN) & $R^2$ & Precision & Recall & F1 & AUC \\",
        r"\midrule",
    ]
    for r in tree["rows"]:
        if r["task"] == "A":
            lines.append(f"{r['model']} (Task A) & {fmt_int(r['RMSE_AZN'])} & {fmt_int(r['MAE_AZN'])} & {r['R2']:.3f} & & & & \\\\")
    lines.append(r"\midrule")
    for r in tree["rows"]:
        if r["task"] == "B":
            lines.append(f"{r['model']} (Task B) & & & & {r['Precision']:.3f} & {r['Recall']:.3f} & {r['F1']:.3f} & {r['AUC']:.3f} \\\\")
    for name, m in svm_test.items():
        if "Tree" in name:
            continue
        lines.append(f"{tex(name)} & & & & {m['Precision']:.3f} & {m['Recall']:.3f} & {m['F1']:.3f} & {m['AUC']:.3f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]

    lines += [
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{5-fold cross-validation on train+validation (mean $\pm$ std; scaler refit inside each fold). "
        r"Task A uses log(price). Times are mean seconds per fold.}",
        r"\label{tab:cv}",
        r"\begin{tabular}{@{}lrrrr@{}}",
        r"\toprule",
        r"Task B model & F1 & AUC & fit (s) & predict (s) \\",
        r"\midrule",
    ]
    for name, r in cv_b.items():
        lines.append(f"{tex(name)} & {r['F1']:.3f} $\\pm$ {r['F1_std']:.3f} & {r['AUC']:.3f} $\\pm$ {r['AUC_std']:.3f} "
                     f"& {r['fit_s']:.2f} & {r['pred_s']:.2f} \\\\")
    lines += [r"\midrule", r"Task A model & RMSE (log) & $R^2$ (log) & fit (s) & predict (s) \\", r"\midrule"]
    for name, r in cv_a.items():
        lines.append(f"{tex(name)} & {r['RMSE']:.3f} $\\pm$ {r['RMSE_std']:.3f} & {r['R2']:.3f} $\\pm$ {r['R2_std']:.3f} "
                     f"& {r['fit_s']:.2f} & {r['pred_s']:.2f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    path = os.path.join(REPORT_DIR, "results_table.tex")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("saved", path)


def main() -> None:
    os.makedirs(RES_DIR, exist_ok=True)
    os.makedirs(os.path.join(REPORT_DIR, "figures"), exist_ok=True)

    print("========== 1. data ==========")
    d = dp.prepare()
    with open(os.path.join(RES_DIR, "data_summary.json"), "w", encoding="utf-8") as f:
        json.dump(d["info"], f, indent=2, ensure_ascii=False)

    print("\n========== 2. EDA ==========")
    eda.make_all(d)

    print("\n========== 3. decision tree (Task A + Task B) ==========")
    tree = tx.run(d, train_cap=TREE_TRAIN_CAP)

    print("\n========== 4. SVM + benchmark (Task B, CV for all models) ==========")
    svm_test, cv_b, cv_a = svx.run(
        d["X_tr"], d["X_val"], d["X_te"], d["y_tr"], d["y_val"], d["y_te"], d["thr"], d["names"],
        tree_clf_args=tree["classification_args"], tree_reg_args=tree["regression_args"],
    )

    print("\n========== 5. final tables ==========")
    task_a = {f"{r['model']}": {k: r[k] for k in ("RMSE_AZN", "MAE_AZN", "R2")} for r in tree["rows"] if r["task"] == "A"}
    task_b = {f"{r['model']} (5k fit)": {k: r[k] for k in ("Precision", "Recall", "F1", "AUC")} for r in tree["rows"] if r["task"] == "B"}
    task_b.update({k: v for k, v in svm_test.items() if "Tree" not in k})
    print("\n=== Task A: test set (price, AZN) ===")
    ev.compare(task_a, os.path.join(RES_DIR, "final_task_a.csv"))
    print("\n=== Task B: test set (price tier) ===")
    ev.compare(task_b, os.path.join(RES_DIR, "final_task_b.csv"))

    write_numbers(d, tree, svm_test)
    write_results_table(tree, svm_test, cv_b, cv_a)
    print("\ndone. all numbers and figures above are reproduced by: python -m src.run_all")


if __name__ == "__main__":
    main()
